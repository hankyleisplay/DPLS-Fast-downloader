let currentLang = 'zh-TW';

function detectInitialLanguage() {
  const browserLang = navigator.language || navigator.userLanguage || '';
  if (browserLang.startsWith('zh-CN') || browserLang.startsWith('zh-SG') || browserLang === 'zh') {
    return 'zh-CN';
  } else if (browserLang.startsWith('zh')) {
    return 'zh-TW';
  } else if (browserLang.startsWith('ja')) {
    return 'ja-JP';
  } else if (browserLang.startsWith('en')) {
    return 'en-US';
  }
  return 'zh-TW';
}

function t(key) {
  const dict = I18N_LOCALES[currentLang] || I18N_LOCALES['zh-TW'];
  return dict[key] || key;
}

function setLanguage(lang) {
  if (!I18N_LOCALES[lang]) lang = 'zh-TW';
  currentLang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.getAttribute('data-i18n');
    if (k) el.textContent = t(k);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const k = el.getAttribute('data-i18n-placeholder');
    if (k) el.setAttribute('placeholder', t(k));
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const k = el.getAttribute('data-i18n-title');
    if (k) el.setAttribute('title', t(k));
  });

  // Save preference
  if (typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local) {
    chrome.storage.local.set({ dpls_language: lang });
  }
}
